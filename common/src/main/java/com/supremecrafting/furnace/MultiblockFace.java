package com.supremecrafting.furnace;

/**
 * The six faces of a Supreme Furnace, expressed relative to its {@code front}
 * direction (not world directions). Vanilla furnace uses three distinct
 * textures: {@code furnace_top} (TOP+BOTTOM), {@code furnace_front} (FRONT),
 * {@code furnace_side} (BACK+LEFT+RIGHT).
 */
public enum MultiblockFace {
    TOP, BOTTOM, FRONT, BACK, LEFT, RIGHT
}
